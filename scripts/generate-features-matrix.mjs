#!/usr/bin/env node
/**
 * Generate docs/FEATURES.md from the ops/features.json feature ledger.
 *
 *   node scripts/generate-features-matrix.mjs            run each feature's verify tests, write the doc
 *   node scripts/generate-features-matrix.mjs --no-run   static: only check the verify test files exist
 *   node scripts/generate-features-matrix.mjs --check    fail (exit 1) if docs/FEATURES.md would change
 *
 * Presence on this checkout is authoritative only from a test run (squash-merges and
 * cherry-picks change SHAs, so git ancestry can't answer it); main/dev/prod columns
 * show the hand-curated `since` landing SHAs. `--check` regenerates in the same mode
 * (combine with --no-run for a fast static gate against a --no-run generated doc).
 *
 * Exit codes: 0 ok, 1 --check found a difference, 2 invalid ledger.
 */
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LEDGER = path.join(REPO_ROOT, "ops", "features.json");
const OUTPUT = path.join(REPO_ROOT, "docs", "FEATURES.md");
const LINEAGES = ["main", "dev", "prod"];
const STATUS_LABELS = {
  present: "✅ present",
  absent: "❌ absent",
  "missing-test": "⚠️ missing-test",
  "not-run": "⏸ not-run",
};

function loadLedger() {
  const ledger = JSON.parse(readFileSync(LEDGER, "utf8"));
  if (!Array.isArray(ledger.features))
    throw new Error("ops/features.json: `features` must be an array");
  for (const feature of ledger.features) {
    if (!feature.id || !feature.title)
      throw new Error("ops/features.json: every feature needs id + title");
    if (!Array.isArray(feature.verify) || feature.verify.length === 0) {
      throw new Error(`ops/features.json: ${feature.id} needs a non-empty verify array`);
    }
  }
  return ledger;
}

function verifyFeature(feature, run) {
  const missing = feature.verify.filter((file) => !existsSync(path.join(REPO_ROOT, file)));
  if (missing.length > 0) return { status: "missing-test", missing };
  if (!run) return { status: "not-run" };
  const result = spawnSync(process.execPath, ["--import", "tsx/esm", "--test", ...feature.verify], {
    cwd: REPO_ROOT,
    encoding: "utf8",
    timeout: 15 * 60_000,
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.status === 0) return { status: "present" };
  const tail = `${result.stdout ?? ""}${result.stderr ?? ""}`
    .trim()
    .split("\n")
    .slice(-15)
    .join("\n");
  return { status: "absent", detail: result.error?.message ?? tail };
}

function upstreamCell(upstream) {
  if (!upstream || upstream === "absent") return "—";
  const imported = /^imported#(\d+)$/.exec(upstream);
  return imported ? `imported #${imported[1]}` : upstream;
}

function sinceCell(since, lineage) {
  const sha = since?.[lineage];
  return sha ? `✅ \`${sha}\`` : "·";
}

const escapeCell = (text) => String(text).replace(/\|/g, "\\|");

function render(ledger, results, run) {
  const lines = [
    "<!-- GENERATED by scripts/generate-features-matrix.mjs from ops/features.json — do not edit by hand. -->",
    "",
    "# Feature Matrix",
    "",
    "Code-feature presence across lineages. Runtime feature flags are tracked separately in",
    "`ops/flags.expect.json` (see `scripts/flags-drift.mjs`).",
    "",
    `- **This checkout** — ${run ? "result of running each feature's `verify` tests" : "static check only (`--no-run`): verify test files exist, tests not executed"}.`,
    "- **main / dev / prod** — hand-curated landing SHA from `since`; `·` = not recorded (not a claim of absence).",
    "",
    "| Feature | Upstream | main | dev | prod | This checkout | Verify |",
    "| --- | --- | --- | --- | --- | --- | --- |",
  ];
  for (const feature of ledger.features) {
    const { status } = results.get(feature.id);
    const verify = feature.verify.map((file) => `\`${path.basename(file)}\``).join("<br>");
    lines.push(
      `| ${[
        `**${escapeCell(feature.id)}**<br>${escapeCell(feature.title)}${feature.pr ? ` (#${feature.pr})` : ""}`,
        upstreamCell(feature.upstream),
        ...LINEAGES.map((lineage) => sinceCell(feature.since, lineage)),
        STATUS_LABELS[status],
        verify,
      ].join(" | ")} |`
    );
  }
  lines.push("", "## Details", "");
  for (const feature of ledger.features) {
    lines.push(`### ${feature.id}`, "", escapeCell(feature.description ?? feature.title), "");
    if (feature.surfaces?.length)
      lines.push(`- Surfaces: ${feature.surfaces.map((s) => `\`${s}\``).join(", ")}`);
    if (feature.flags?.length)
      lines.push(`- Flags: ${feature.flags.map((f) => `\`${f}\``).join(", ")}`);
    lines.push(`- Verify: ${feature.verify.map((file) => `\`${file}\``).join(", ")}`, "");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

function main() {
  const args = new Set(process.argv.slice(2));
  for (const arg of args) {
    if (!["--no-run", "--check", "-h", "--help"].includes(arg)) {
      console.error(`generate-features-matrix: unknown argument ${arg}`);
      return 2;
    }
  }
  if (args.has("-h") || args.has("--help")) {
    console.log("Usage: node scripts/generate-features-matrix.mjs [--no-run] [--check]");
    return 0;
  }
  const run = !args.has("--no-run");
  let ledger;
  try {
    ledger = loadLedger();
  } catch (error) {
    console.error(`generate-features-matrix: ${error.message}`);
    return 2;
  }

  const results = new Map();
  for (const feature of ledger.features) {
    const result = verifyFeature(feature, run);
    results.set(feature.id, result);
    console.log(`${feature.id}: ${result.status}`);
    if (result.missing) console.log(`  missing: ${result.missing.join(", ")}`);
    if (result.detail) console.log(result.detail.replace(/^/gm, "  "));
  }

  const content = render(ledger, results, run);
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, "utf8") : null;
  const rel = path.relative(REPO_ROOT, OUTPUT);
  if (args.has("--check")) {
    if (current === content) {
      console.log(`${rel} is up to date`);
      return 0;
    }
    console.error(
      `${rel} is stale — run: node scripts/generate-features-matrix.mjs${run ? "" : " --no-run"}`
    );
    return 1;
  }
  if (current !== content) writeFileSync(OUTPUT, content);
  console.log(`${current === content ? "unchanged" : "wrote"} ${rel}`);
  return 0;
}

process.exitCode = main();
